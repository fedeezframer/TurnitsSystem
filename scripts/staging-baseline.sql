CREATE OR REPLACE FUNCTION public.asignar_slug_unico()
 RETURNS trigger
 LANGUAGE plpgsql
 SET search_path TO 'pg_catalog', 'public'
AS $function$
DECLARE
  base   text;
  prueba text;
  sufijo integer := 2;
BEGIN
  IF NEW.slug IS NOT NULL AND NEW.slug <> '' THEN RETURN NEW; END IF;
  base   := generar_slug_base(NEW.business_name);
  prueba := base;
  WHILE EXISTS (SELECT 1 FROM usuarios WHERE slug = prueba) LOOP
    prueba := base || '-' || sufijo;
    sufijo := sufijo + 1;
  END LOOP;
  NEW.slug := prueba;
  RETURN NEW;
END;
$function$
;
