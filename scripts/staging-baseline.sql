CREATE OR REPLACE FUNCTION public.activar_compra_plan(p_usuario_id uuid, p_slug text, p_plan text, p_dias integer, p_payment_id text, p_importe numeric, p_compra_id uuid DEFAULT NULL::uuid)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
DECLARE
  u public.usuarios%ROWTYPE;
  c public.compras_planes%ROWTYPE;
  nueva timestamptz;
  eliminados integer;
BEGIN
  IF p_plan NOT IN ('basico','premium') OR p_dias NOT IN (30,365) OR p_payment_id IS NULL OR p_payment_id = '' THEN
    RAISE EXCEPTION 'Compra inválida';
  END IF;
  SELECT * INTO u FROM public.usuarios WHERE id=p_usuario_id AND slug=p_slug FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Cuenta no encontrada'; END IF;
  IF EXISTS(SELECT 1 FROM public.renovaciones_procesadas WHERE payment_id=p_payment_id) THEN
    RETURN jsonb_build_object('aplicada',false,'fecha_vencimiento',u.fecha_vencimiento);
  END IF;
  IF p_compra_id IS NOT NULL THEN
    SELECT * INTO c FROM public.compras_planes WHERE id=p_compra_id FOR UPDATE;
    IF NOT FOUND OR c.usuario_id<>u.id OR c.slug<>p_slug OR c.plan<>p_plan OR c.dias<>p_dias OR c.importe<>p_importe THEN
      RAISE EXCEPTION 'El pago no coincide con la compra';
    END IF;
    IF c.fecha_activada IS NOT NULL OR (c.payment_id IS NOT NULL AND c.payment_id<>p_payment_id) THEN
      RAISE EXCEPTION 'Compra ya utilizada con otro pago';
    END IF;
  END IF;
  nueva := (CASE WHEN u.plan=p_plan AND u.estado_suscripcion<>'trial' AND u.fecha_vencimiento>now()
    THEN u.fecha_vencimiento ELSE now() END) + make_interval(days=>p_dias);
  INSERT INTO public.renovaciones_procesadas(payment_id,slug) VALUES(p_payment_id,p_slug);
  eliminados := public.aplicar_limites_plan(p_slug,p_plan);
  UPDATE public.usuarios SET plan=p_plan,estado_suscripcion='activo',fecha_vencimiento=nueva,premium_promo=false WHERE id=u.id;
  IF p_compra_id IS NOT NULL THEN
    UPDATE public.compras_planes SET estado='approved',payment_id=p_payment_id,fecha_activada=now() WHERE id=p_compra_id;
  END IF;
  RETURN jsonb_build_object('aplicada',true,'fecha_vencimiento',nueva,'miembros_eliminados',eliminados);
END $function$
;
CREATE OR REPLACE FUNCTION public.turnits_limitar_equipo_basico()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
DECLARE
  plan_negocio text;
  miembros integer;
BEGIN
  IF NEW.es_dueño IS TRUE THEN RETURN NEW; END IF;
  IF TG_OP = 'UPDATE' THEN
    IF OLD.slug IS NOT DISTINCT FROM NEW.slug AND OLD.es_dueño IS NOT DISTINCT FROM NEW.es_dueño THEN
      RETURN NEW;
    END IF;
  END IF;
  PERFORM pg_advisory_xact_lock(hashtextextended('turnits-team:' || NEW.slug, 0));
  SELECT plan INTO plan_negocio FROM public.usuarios WHERE slug = NEW.slug FOR UPDATE;
  IF plan_negocio = 'basico' THEN
    SELECT count(*) INTO miembros FROM public.equipo
      WHERE slug = NEW.slug AND es_dueño IS FALSE AND id IS DISTINCT FROM NEW.id;
    IF miembros >= 2 THEN
      RAISE EXCEPTION 'Básico incluye al titular y hasta 2 miembros adicionales. Ampliá a Premium.' USING ERRCODE = '23514';
    END IF;
  END IF;
  RETURN NEW;
END $function$
;
