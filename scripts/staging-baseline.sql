CREATE VIEW public."negocio_resumen" WITH (security_invoker=true) AS  SELECT id,
    slug,
    business_name,
    nombre_persona,
    apellido,
    email,
    telefono,
    activo,
    plan,
    metodo_pago,
    estado_suscripcion,
    fecha_vencimiento,
    (mp_access_token IS NOT NULL) AS tiene_mp,
    ( SELECT count(*) AS count
           FROM servicios s
          WHERE ((s.slug = u.slug) AND ((s.activo)::text = 'true'::text))) AS total_servicios,
    ( SELECT count(*) AS count
           FROM turnos t
          WHERE ((t.slug = u.slug) AND (t.estado <> 'cancelado'::text))) AS total_turnos,
    ( SELECT count(*) AS count
           FROM turnos t
          WHERE ((t.slug = u.slug) AND (t.estado <> 'cancelado'::text) AND (t.fecha >= CURRENT_DATE))) AS turnos_proximos,
    ( SELECT COALESCE(sum(t.monto_pagado), (0)::numeric) AS "coalesce"
           FROM turnos t
          WHERE ((t.slug = u.slug) AND (t.estado <> 'cancelado'::text) AND (t.pago_estado = 'aprobado'::text))) AS volumen_total
   FROM usuarios u;
CREATE VIEW public."referidos_detalle" WITH (security_invoker=true) AS  SELECT r.created_at AS registrado_at,
    r.grupo_nro,
    ur.business_name AS referidor_negocio,
    r.referidor_slug,
    ui.business_name AS invitado_negocio,
    r.invitado_slug,
    ui.email AS invitado_email,
    ui.plan AS invitado_plan,
    r.premio_entregado_at
   FROM ((referidos r
     JOIN usuarios ur ON ((ur.slug = r.referidor_slug)))
     JOIN usuarios ui ON ((ui.slug = r.invitado_slug)))
  ORDER BY r.created_at DESC;
CREATE VIEW public."turnits_vip_candidatos" WITH (security_invoker=true) AS  SELECT u.slug,
    u.business_name,
    u.email,
    u.plan,
    u.created_at,
    COALESCE(sum(t.monto_pagado) FILTER (WHERE ((t.pago_estado = 'aprobado'::text) AND (t.estado <> 'cancelado'::text))), (0)::numeric) AS recaudacion_total,
    count(t.id) FILTER (WHERE (t.estado = ANY (ARRAY['confirmado'::text, 'completado'::text]))) AS turnos_confirmados
   FROM (usuarios u
     LEFT JOIN turnos t ON ((t.slug = u.slug)))
  GROUP BY u.id, u.slug, u.business_name, u.email, u.plan, u.created_at;
