const assert = require("node:assert/strict");
(async () => {
  const { bookingReceipt, receiptHome, receiptDate } = await import("../web/src/shared/booking-receipt.js");
  const reservation = { id: "receipt-test", nombre: "Ana", apellido: "Gómez", fecha: "2026-10-21", hora: "15:30:00", servicio_nombre: "Corte", precio_cobrado: 12500, monto_pagado: 3750, pago_estado: "aprobado", estado: "confirmado", metodo_pago: "mercadopago", extras: [{ nombre: "Shampoo", cantidad: 2, precio: 2500 }] };
  const partial = bookingReceipt(reservation);
  assert.equal(partial.total, 12500);
  assert.equal(partial.paid, 3750);
  assert.equal(partial.due, 8750);
  const quoted = bookingReceipt({ ...reservation, presupuesto_detalle: "[servicio:Tatuaje%20acordado]\nDiseño final de 10 cm" });
  assert(quoted.rows.some(([label, value]) => label === "Servicio" && value === "Tatuaje acordado"));
  assert(quoted.rows.some(([label, value]) => label === "Detalle acordado" && value === "Diseño final de 10 cm"));
  assert.equal(partial.extras[0].total, 2500);
  assert(partial.rows.some(([label, value]) => label === "Reservó" && value === "Ana Gómez"));
  assert.equal(bookingReceipt({ ...reservation, monto_pagado: 12500 }).due, 0);
  assert.equal(bookingReceipt({ ...reservation, monto_pagado: 15000 }).due, 0);
  const pending = bookingReceipt({ ...reservation, monto_pagado: 0, pago_estado: "pendiente" });
  assert.equal(pending.due, 12500);
  assert.match(pending.note, /verificación/);
  assert.match(bookingReceipt({ ...reservation, estado: "cancelado" }).note, /reintegros/);
  assert.match(bookingReceipt({ ...reservation, pago_estado: "reembolsado" }).note, /reembolsado/);
  assert.equal(bookingReceipt({ ...reservation, precio_cobrado: 0, monto_pagado: 0 }).total, 0);
  assert.equal(bookingReceipt({ ...reservation, precio_cobrado: "not-a-number" }).total, 0);
  assert.match(receiptDate("2026-10-21"), /2026/);
  assert.equal(receiptDate("invalid"), "Sin fecha");
  const session = values => ({ getItem: key => values[key] || null });
  assert.equal(receiptHome(session({ access_token: "token", account_type: "usuario" })), "/browse");
  assert.equal(receiptHome(session({ access_token: "token", account_type: "negocio" })), "/app");
  assert.equal(receiptHome(session({})), "/");
  assert.equal(receiptHome({ getItem() { throw new Error("Storage blocked"); } }), "/");
  const { createReceiptPdf } = await import("../web/src/shared/receipt-pdf.js");
  const pdf = await createReceiptPdf(reservation);
  assert.match(pdf.output(), /%PDF-/);
  const logo = new Uint8Array(require("node:fs").readFileSync(require("node:path").join(__dirname, "../web/public/assets/browse/LogoTurnitsCompletoB.png")));
  const branded = await createReceiptPdf(reservation, logo);
  assert.match(branded.output(), /\/Subtype \/Image/);
  assert(!branded.output().includes("Confirmado"));
  assert(!branded.output().includes(" ARS"));
  const long = await createReceiptPdf({ ...reservation, extras: Array.from({ length: 90 }, (_, index) => ({ nombre: `Producto ${index} con una descripción extensa`, precio: 10 })) });
  assert(long.getNumberOfPages() > 1);
  console.log("PASS receipt: shared amounts, partial/full/pending/refunded payments, product quantities, return routes and paginated PDF.");
})().catch(error => { console.error(error); process.exitCode = 1; });
